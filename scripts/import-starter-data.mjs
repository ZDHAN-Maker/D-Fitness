#!/usr/bin/env node
/**
 * Converts the starter dataset (JSON) into a Supabase migration that loads it into the MASTER tables,
 * preserving the ORIGINAL IDs.
 *
 *   1. Put the JSON files in scripts/starter-data/
 *   2. Edit scripts/starter-data.mapping.json to match their shape
 *   3. npm run seed:import          -> writes supabase/migrations/012_starter_dataset.sql
 *   4. npm run db:reset             (or `supabase db push`)
 *
 * The generated migration:
 *   - deletes the baseline rows from 010 (source_id like 'seed:%') for every imported table,
 *   - inserts starter rows with explicit ids (ON CONFLICT (id) DO UPDATE => safe to re-run),
 *   - resets the identity sequences so later inserts never collide.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'scripts', 'starter-data');
const mapping = JSON.parse(readFileSync(path.join(root, 'scripts', 'starter-data.mapping.json'), 'utf8'));

// Parents first for inserts; children first for deletes.
const ORDER = ['units', 'food_categories', 'food_items', 'food_servings', 'exercise_categories', 'exercises',
  'activity_types', 'goal_templates', 'achievement_definitions'];

const slug = (v) => String(v).toLowerCase().normalize('NFKD').replace(/[^\w\s-]/g, '').trim().replace(/[\s_]+/g, '-');
const transforms = {
  number: (v) => (v === null || v === undefined || v === '' ? null : Number(v)),
  string: (v) => (v == null ? null : String(v)),
  boolean: (v) => v === true || v === 1 || v === '1' || String(v).toLowerCase() === 'true',
  array: (v) => (Array.isArray(v) ? v : v ? String(v).split(/[,;|]/).map((x) => x.trim()).filter(Boolean) : []),
  slug,
};

function lit(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') { if (!Number.isFinite(value)) throw new Error(`Non-finite number: ${value}`); return String(value); }
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value)) return value.length ? `array[${value.map(lit).join(',')}]::text[]` : `'{}'::text[]`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function pick(row, spec) {
  if (spec && typeof spec === 'object' && 'const' in spec) return spec.const;
  const field = typeof spec === 'string' ? spec : spec.field;
  const raw = row[field];
  const fn = typeof spec === 'object' && spec.transform ? transforms[spec.transform] : null;
  return fn ? fn(raw) : raw === undefined ? null : raw;
}

const present = ORDER.filter((t) => mapping.tables[t] && existsSync(path.join(dataDir, mapping.tables[t].file)));
if (present.length === 0) {
  console.error(`No starter files found in ${dataDir}.\nCopy your JSON files there and adjust scripts/starter-data.mapping.json.`);
  process.exit(1);
}

const out = [`-- 012_starter_dataset.sql (GENERATED by scripts/import-starter-data.mjs on ${new Date().toISOString()})`,
  '-- Do not edit by hand; re-run the importer instead.', ''];

for (const t of [...present].reverse()) {
  out.push(`delete from public.${t} where source_id like 'seed:%';`);
}
out.push('');

for (const t of present) {
  const cfg = mapping.tables[t];
  let rows = JSON.parse(readFileSync(path.join(dataDir, cfg.file), 'utf8'));
  if (cfg.rows) for (const key of cfg.rows.split('.')) rows = rows?.[key];
  if (!Array.isArray(rows)) throw new Error(`${t}: "${cfg.rows}" in ${cfg.file} is not an array`);

  const cols = Object.keys(cfg.columns);
  const allCols = cfg.id ? ['id', ...cols] : cols;
  const updates = cols.map((c) => `${c} = excluded.${c}`).join(', ');
  const values = rows.map((row) => {
    const vals = cols.map((c) => lit(pick(row, cfg.columns[c])));
    if (cfg.id) vals.unshift(lit(Number(row[cfg.id])));
    return `  (${vals.join(', ')})`;
  });

  out.push(`-- ${t}: ${rows.length} rows`);
  // 500 rows per statement keeps statements a sane size.
  for (let i = 0; i < values.length; i += 500) {
    out.push(`insert into public.${t} (${allCols.join(', ')}) overriding system value values`);
    out.push(values.slice(i, i + 500).join(',\n'));
    out.push(cfg.id ? `on conflict (id) do update set ${updates};` : 'on conflict do nothing;', '');
  }
  if (cfg.id) {
    out.push(`select setval(pg_get_serial_sequence('public.${t}', 'id'), greatest((select coalesce(max(id), 1) from public.${t}), 1));`, '');
  }
}

const target = path.join(root, 'supabase', 'migrations', '012_starter_dataset.sql');
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${path.relative(root, target)} (${present.join(', ')})`);
