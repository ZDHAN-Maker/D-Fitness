-- 002_master_tables.sql
-- MASTER / REFERENCE DATA. Shared by all users, read-only for clients.
--
-- ID strategy: every master table has `id bigint identity (BY DEFAULT)` so the
-- original starter-dataset IDs can be inserted explicitly and preserved.
-- If the dataset uses non-numeric IDs they are kept in `source_id`.
-- Rows created by 010_seed_master_data.sql carry source_id = 'seed:<slug>' so the
-- starter import can replace them cleanly.

create table public.units (
  id             bigint generated by default as identity primary key,
  source_id      text unique,
  code           text not null unique,
  name           text not null,
  kind           text not null check (kind in ('mass','volume','portion','length','time','energy')),
  base_unit_code text,                                   -- 'g' for mass, 'ml' for volume
  to_base_factor numeric(14,6) check (to_base_factor is null or to_base_factor > 0),
  created_at     timestamptz not null default now()
);
comment on table public.units is
  'Measurement units. mass->g, volume->ml via to_base_factor. kind=portion (bowl, slice, egg...) has no fixed factor; use food_servings.';

create table public.food_categories (
  id         bigint generated by default as identity primary key,
  source_id  text unique,
  slug       text not null unique,
  name       text not null,
  parent_id  bigint references public.food_categories(id) on delete set null,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table public.food_items (
  id            bigint generated by default as identity primary key,
  source_id     text unique,
  category_id   bigint references public.food_categories(id) on delete set null,
  name          text not null,
  brand         text,
  barcode       text,
  -- Nutrition values are expressed PER base_quantity of base_unit (default: per 100 g).
  base_quantity numeric(10,2) not null default 100 check (base_quantity > 0),
  base_unit     text not null default 'g' check (base_unit in ('g','ml')),
  calories      numeric(8,2) not null check (calories >= 0),
  protein_g     numeric(8,2) not null default 0 check (protein_g >= 0),
  carbs_g       numeric(8,2) not null default 0 check (carbs_g >= 0),
  fat_g         numeric(8,2) not null default 0 check (fat_g >= 0),
  fiber_g       numeric(8,2) not null default 0 check (fiber_g >= 0),
  sugar_g       numeric(8,2) check (sugar_g >= 0),
  sodium_mg     numeric(10,2) check (sodium_mg >= 0),
  data_source   text not null default 'starter',
  is_verified   boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table public.food_servings (
  id          bigint generated by default as identity primary key,
  source_id   text unique,
  food_item_id bigint not null references public.food_items(id) on delete cascade,
  label       text not null,                              -- e.g. '1 bowl', '1 egg'
  unit_code   text not null references public.units(code) on update cascade,
  quantity    numeric(10,3) not null default 1 check (quantity > 0),
  -- grams (or ml, per the food's base_unit) equivalent of `quantity` x `unit_code`
  base_amount numeric(10,2) not null check (base_amount > 0),
  is_default  boolean not null default false,
  sort_order  int not null default 0,
  unique (food_item_id, label)
);

create table public.exercise_categories (
  id         bigint generated by default as identity primary key,
  source_id  text unique,
  slug       text not null unique,
  name       text not null,
  sort_order int not null default 0
);

create table public.exercises (
  id                bigint generated by default as identity primary key,
  source_id         text unique,
  category_id       bigint references public.exercise_categories(id) on delete set null,
  name              text not null,
  primary_muscle    text,
  secondary_muscles text[] not null default '{}',
  equipment         text,
  difficulty        text check (difficulty in ('beginner','intermediate','advanced')),
  movement_type     text,                                 -- push | pull | squat | hinge | carry | core | cardio ...
  tracking_mode     text not null default 'weight_reps'
                    check (tracking_mode in ('weight_reps','reps_only','duration','distance_duration','weight_duration')),
  instructions      text,
  image_url         text,
  video_url         text,
  data_source       text not null default 'starter',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create table public.activity_types (
  id             bigint generated by default as identity primary key,
  source_id      text unique,
  slug           text not null unique,
  name           text not null,
  category       text,                                    -- cardio | sport | mind_body ...
  met_value      numeric(5,2) check (met_value > 0),       -- for calorie estimation
  tracks_distance boolean not null default false,
  tracks_pace     boolean not null default false,
  icon           text,
  created_at     timestamptz not null default now()
);

create table public.goal_templates (
  id                    bigint generated by default as identity primary key,
  source_id             text unique,
  goal_type             text not null check (goal_type in ('body','strength','running','nutrition','habit')),
  title                 text not null,
  description           text,
  metric                text not null,                     -- weight_kg | body_fat_pct | one_rep_max_kg | run_time_min | daily_protein_g | workouts_per_week ...
  direction             text not null default 'increase' check (direction in ('increase','decrease')),
  default_unit          text,
  default_target        numeric,
  default_duration_days int check (default_duration_days > 0),
  config                jsonb not null default '{}'::jsonb,
  created_at            timestamptz not null default now()
);

create table public.achievement_definitions (
  id          bigint generated by default as identity primary key,
  source_id   text unique,
  code        text not null unique,
  name        text not null,
  description text,
  category    text,
  icon        text,
  -- Evaluated server-side by public.evaluate_achievements(): metric >= threshold.
  metric      text not null,
  threshold   numeric not null check (threshold > 0),
  sort_order  int not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);
